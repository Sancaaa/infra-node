// ProviderVersion is the pinned bpg/proxmox version written to versions.tf.
const ProviderVersion = "0.73.2"

// InstallHint is shown when the terraform binary is not in PATH.
const InstallHint = "Terraform is not installed on this server. Install it from HashiCorp's apt repository (see docs/deploy.md) so the dashboard can create and manage Proxmox machines."

// MachineSpec is one entry in machines.auto.tfvars.json (var.machines).
type MachineSpec struct {
	Node     string `json:"node"`
	Cores    int    `json:"cores"`
	Memory   int    `json:"memory"`
	DiskGB   int    `json:"disk_gb"`
	Storage  string `json:"storage"`
	Bridge   string `json:"bridge"`
	Template string `json:"template"`
	OSType   string `json:"os_type"`
	IPMode   string `json:"ip_mode"`
	IPCIDR   string `json:"ip_cidr"`
	Gateway  string `json:"gateway"`
}

// Input is everything needed to render terraform/. The Proxmox token secret is
// not here: it stays in secrets/proxmox.tfvars.json (mode 0600).
type Input struct {
	Endpoint     string
	TokenID      string
	Insecure     bool
	SSHPublicKey string
	Machines     map[string]MachineSpec
}

// managedFiles is the fixed order for View code. State files, .terraform/,
// plans/ and secrets are never part of this list.
var managedFiles = []string{"versions.tf", "provider.tf", "main.tf", "machines.auto.tfvars.json"}

const versionsTF = `# Generated by infra-manager. Do not edit by hand.

terraform {
  required_version = ">= 1.5.0"

  required_providers {
    proxmox = {
      source  = "bpg/proxmox"
      version = "` + ProviderVersion + `"
    }
  }
}
`

const providerTF = `# Generated by infra-manager. Do not edit by hand.
# The API token secret is passed separately from secrets/proxmox.tfvars.json (0600).

provider "proxmox" {
  endpoint  = var.proxmox_endpoint
  api_token = "${var.proxmox_token_id}=${var.proxmox_token_secret}"
  insecure  = var.proxmox_insecure
}

variable "proxmox_endpoint"     { type = string }
variable "proxmox_token_id"     { type = string }
variable "proxmox_token_secret" { type = string; sensitive = true }
variable "proxmox_insecure"     { type = bool; default = false }
variable "ssh_public_key"       { type = string }
`

const mainTF = `# Generated by infra-manager. Do not edit by hand.

variable "machines" {
  type = map(object({
    node     = string
    cores    = number
    memory   = number
    disk_gb  = number
    storage  = string
    bridge   = string
    template = string
    os_type  = string
    ip_mode  = string
    ip_cidr  = string
    gateway  = string
  }))
  default = {}
}

resource "proxmox_virtual_environment_container" "machine" {
  for_each = var.machines

  description   = "Managed by infra-manager"
  node_name     = each.value.node
  unprivileged  = true
  started       = true
  start_on_boot = true

  # Ignore runtime power state and creation-only fields that Proxmox does not
  # read back (so Start/Stop and Adopt do not produce spurious diffs).
  lifecycle {
    ignore_changes = [
      started,
      description,
      operating_system[0].template_file_id,
      initialization[0].user_account,
    ]
  }

  features { nesting = true }
  cpu      { cores = each.value.cores }
  memory   { dedicated = each.value.memory; swap = 512 }
  disk     { datastore_id = each.value.storage; size = each.value.disk_gb }

  network_interface {
    name   = "eth0"
    bridge = each.value.bridge
  }

  operating_system {
    template_file_id = each.value.template
    type             = each.value.os_type
  }

  initialization {
    hostname = each.key

    ip_config {
      ipv4 {
        address = each.value.ip_mode == "static" ? each.value.ip_cidr : "dhcp"
        gateway = each.value.ip_mode == "static" && each.value.gateway != "" ? each.value.gateway : null
      }
    }

    user_account {
      keys = [var.ssh_public_key]
    }
  }
}

output "machines" {
  value = {
    for name, c in proxmox_virtual_environment_container.machine : name => {
      vm_id     = c.vm_id
      node_name = c.node_name
      ipv4      = try(c.ipv4["eth0"], "")
    }
  }
}
`

func InferOSType(template string) string {
	if strings.Contains(strings.ToLower(template), "ubuntu") {
		return "ubuntu"
	}
	return "debian"
}

func Render(in Input) (map[string]string, error) {
	machines := in.Machines
	if machines == nil {
		machines = map[string]MachineSpec{}
	}
	raw, err := json.MarshalIndent(struct {
		Endpoint     string                 `json:"proxmox_endpoint"`
		TokenID      string                 `json:"proxmox_token_id"`
		Insecure     bool                   `json:"proxmox_insecure"`
		SSHPublicKey string                 `json:"ssh_public_key"`
		Machines     map[string]MachineSpec `json:"machines"`
	}{in.Endpoint, in.TokenID, in.Insecure, strings.TrimSpace(in.SSHPublicKey), machines}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode machines.auto.tfvars.json: %w", err)
	}
	return map[string]string{
		"versions.tf":               versionsTF,
		"provider.tf":               providerTF,
		"main.tf":                   mainTF,
		"machines.auto.tfvars.json": string(append(raw, '\n')),
	}, nil
}

// Write updates only the four managed files, leaving Terraform's own state,
// lock file and .terraform/ directory untouched.
func Write(dir string, files map[string]string) error {
	for _, name := range managedFiles {
		if content, ok := files[name]; ok {
			if err := writePrivate(filepath.Join(dir, name), []byte(content)); err != nil {
				return fmt.Errorf("write %s: %w", name, err)
			}
		}
	}
	return nil
}

// Read reads only the managed generated files in fixed order for View code.
func Read(dir string) ([][2]string, error) {
	var out [][2]string
	for _, name := range managedFiles {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", name, err)
		}
		out = append(out, [2]string{name, string(data)})
	}
	return out, nil
}

// WriteImport writes a temporary imports.tf block for Adopt (IM8). Both name
// and node must already be validated by CheckMachineName / CheckIdent.
func WriteImport(dir, name, node string, vmid int) error {
	content := fmt.Sprintf("# Temporary import block written by infra-manager for Adopt.\nimport {\n  to = proxmox_virtual_environment_container.machine[%q]\n  id = %q\n}\n",
		name, fmt.Sprintf("%s/%d", node, vmid))
	return writePrivate(filepath.Join(dir, "imports.tf"), []byte(content))
}

// ClearImport removes the temporary imports.tf file if present.
func ClearImport(dir string) {
	_ = os.Remove(filepath.Join(dir, "imports.tf"))
}
